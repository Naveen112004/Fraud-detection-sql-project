USE FRAUD_DETECTION;

SELECT *
FROM TRANSACTIONS;

SELECT *
FROM TRANSACTIONS
WHERE IS_FRAUD = 1;

SELECT
    COUNT(*) AS TOTAL_TRANSACTIONS
FROM TRANSACTIONS;

SELECT
    COUNT(*) AS FRAUD_TRANSACTIONS
FROM TRANSACTIONS
WHERE IS_FRAUD = 1;

SELECT
    SUM(TRANSACTION_AMOUNT) AS TOTAL_TRANSACTION_AMOUNT
FROM TRANSACTIONS;

SELECT
    SUM(TRANSACTION_AMOUNT) AS TOTAL_FRAUD_AMOUNT
FROM TRANSACTIONS
WHERE IS_FRAUD = 1;

SELECT
    AVG(TRANSACTION_AMOUNT) AS AVERAGE_TRANSACTION_AMOUNT
FROM TRANSACTIONS;

SELECT
    MAX(TRANSACTION_AMOUNT) AS HIGHEST_TRANSACTION
FROM TRANSACTIONS;

SELECT
    MIN(TRANSACTION_AMOUNT) AS LOWEST_TRANSACTION
FROM TRANSACTIONS;

SELECT
    TRANSACTION_STATUS,
    COUNT(*) AS TRANSACTION_COUNT
FROM TRANSACTIONS
GROUP BY TRANSACTION_STATUS;

SELECT
    IS_FRAUD,
    COUNT(*) AS TRANSACTION_COUNT
FROM TRANSACTIONS
GROUP BY IS_FRAUD;

SELECT
    ACCOUNT_ID,
    COUNT(*) AS TRANSACTION_COUNT,
    SUM(TRANSACTION_AMOUNT) AS TOTAL_AMOUNT
FROM TRANSACTIONS
GROUP BY ACCOUNT_ID
ORDER BY TOTAL_AMOUNT DESC;

SELECT
    MERCHANT_ID,
    COUNT(*) AS TRANSACTION_COUNT,
    SUM(TRANSACTION_AMOUNT) AS TOTAL_AMOUNT
FROM TRANSACTIONS
GROUP BY MERCHANT_ID
ORDER BY TOTAL_AMOUNT DESC;

SELECT
    PAYMENT_METHOD_ID,
    COUNT(*) AS TRANSACTION_COUNT,
    SUM(TRANSACTION_AMOUNT) AS TOTAL_AMOUNT
FROM TRANSACTIONS
GROUP BY PAYMENT_METHOD_ID
ORDER BY TOTAL_AMOUNT DESC;

SELECT
    ACCOUNT_ID,
    COUNT(*) AS FRAUD_COUNT
FROM TRANSACTIONS
WHERE IS_FRAUD = 1
GROUP BY ACCOUNT_ID
ORDER BY FRAUD_COUNT DESC;

SELECT
    MERCHANT_ID,
    COUNT(*) AS FRAUD_COUNT
FROM TRANSACTIONS
WHERE IS_FRAUD = 1
GROUP BY MERCHANT_ID
ORDER BY FRAUD_COUNT DESC;

SELECT
    PAYMENT_METHOD_ID,
    COUNT(*) AS FRAUD_COUNT
FROM TRANSACTIONS
WHERE IS_FRAUD = 1
GROUP BY PAYMENT_METHOD_ID
ORDER BY FRAUD_COUNT DESC;

SELECT
    DATE(TRANSACTION_DATE) AS TRANSACTION_DAY,
    COUNT(*) AS TRANSACTION_COUNT,
    SUM(TRANSACTION_AMOUNT) AS TOTAL_AMOUNT
FROM TRANSACTIONS
GROUP BY DATE(TRANSACTION_DATE)
ORDER BY TRANSACTION_DAY;

SELECT
    DATE(TRANSACTION_DATE) AS TRANSACTION_DAY,
    COUNT(*) AS FRAUD_COUNT,
    SUM(TRANSACTION_AMOUNT) AS FRAUD_AMOUNT
FROM TRANSACTIONS
WHERE IS_FRAUD = 1
GROUP BY DATE(TRANSACTION_DATE)
ORDER BY TRANSACTION_DAY;

SELECT
    T.TRANSACTION_ID,
    C.CUSTOMER_NAME,
    A.ACCOUNT_ID,
    M.MERCHANT_NAME,
    PM.PAYMENT_METHOD_NAME,
    L.CITY,
    T.TRANSACTION_AMOUNT,
    T.TRANSACTION_DATE,
    T.IS_FRAUD
FROM TRANSACTIONS T
JOIN ACCOUNTS A
    ON T.ACCOUNT_ID = A.ACCOUNT_ID
JOIN CUSTOMERS C
    ON A.CUSTOMER_ID = C.CUSTOMER_ID
JOIN MERCHANTS M
    ON T.MERCHANT_ID = M.MERCHANT_ID
JOIN PAYMENT_METHODS PM
    ON T.PAYMENT_METHOD_ID = PM.PAYMENT_METHOD_ID
JOIN LOCATIONS L
    ON T.LOCATION_ID = L.LOCATION_ID;

SELECT
    C.CUSTOMER_NAME,
    COUNT(T.TRANSACTION_ID) AS TOTAL_TRANSACTIONS,
    SUM(T.TRANSACTION_AMOUNT) AS TOTAL_AMOUNT
FROM CUSTOMERS C
JOIN ACCOUNTS A
    ON C.CUSTOMER_ID = A.CUSTOMER_ID
JOIN TRANSACTIONS T
    ON A.ACCOUNT_ID = T.ACCOUNT_ID
GROUP BY C.CUSTOMER_ID, C.CUSTOMER_NAME
ORDER BY TOTAL_AMOUNT DESC;

SELECT
    C.CUSTOMER_NAME,
    COUNT(T.TRANSACTION_ID) AS FRAUD_TRANSACTIONS,
    SUM(T.TRANSACTION_AMOUNT) AS FRAUD_AMOUNT
FROM CUSTOMERS C
JOIN ACCOUNTS A
    ON C.CUSTOMER_ID = A.CUSTOMER_ID
JOIN TRANSACTIONS T
    ON A.ACCOUNT_ID = T.ACCOUNT_ID
WHERE T.IS_FRAUD = 1
GROUP BY C.CUSTOMER_ID, C.CUSTOMER_NAME
ORDER BY FRAUD_AMOUNT DESC;

SELECT
    M.MERCHANT_NAME,
    M.MERCHANT_CATEGORY,
    COUNT(T.TRANSACTION_ID) AS TOTAL_TRANSACTIONS,
    SUM(T.TRANSACTION_AMOUNT) AS TOTAL_AMOUNT
FROM MERCHANTS M
JOIN TRANSACTIONS T
    ON M.MERCHANT_ID = T.MERCHANT_ID
GROUP BY M.MERCHANT_ID, M.MERCHANT_NAME, M.MERCHANT_CATEGORY
ORDER BY TOTAL_AMOUNT DESC;

SELECT
    M.MERCHANT_NAME,
    COUNT(T.TRANSACTION_ID) AS FRAUD_TRANSACTIONS,
    SUM(T.TRANSACTION_AMOUNT) AS FRAUD_AMOUNT
FROM MERCHANTS M
JOIN TRANSACTIONS T
    ON M.MERCHANT_ID = T.MERCHANT_ID
WHERE T.IS_FRAUD = 1
GROUP BY M.MERCHANT_ID, M.MERCHANT_NAME
ORDER BY FRAUD_AMOUNT DESC;

SELECT
    C.CUSTOMER_NAME,
    T.TRANSACTION_ID,
    T.TRANSACTION_AMOUNT
FROM CUSTOMERS C
JOIN ACCOUNTS A
    ON C.CUSTOMER_ID = A.CUSTOMER_ID
JOIN TRANSACTIONS T
    ON A.ACCOUNT_ID = T.ACCOUNT_ID
WHERE T.TRANSACTION_AMOUNT >
(
    SELECT AVG(TRANSACTION_AMOUNT)
    FROM TRANSACTIONS
);

WITH CUSTOMER_SPENDING AS
(
    SELECT
        A.CUSTOMER_ID,
        SUM(T.TRANSACTION_AMOUNT) AS TOTAL_SPENDING
    FROM ACCOUNTS A
    JOIN TRANSACTIONS T
        ON A.ACCOUNT_ID = T.ACCOUNT_ID
    GROUP BY A.CUSTOMER_ID
)
SELECT
    C.CUSTOMER_NAME,
    CS.TOTAL_SPENDING
FROM CUSTOMER_SPENDING CS
JOIN CUSTOMERS C
    ON CS.CUSTOMER_ID = C.CUSTOMER_ID
ORDER BY CS.TOTAL_SPENDING DESC;

SELECT
    TRANSACTION_ID,
    ACCOUNT_ID,
    TRANSACTION_AMOUNT,
    RANK() OVER (
        ORDER BY TRANSACTION_AMOUNT DESC
    ) AS AMOUNT_RANK
FROM TRANSACTIONS;

SELECT
    TRANSACTION_ID,
    ACCOUNT_ID,
    TRANSACTION_AMOUNT,
    CASE
        WHEN IS_FRAUD = 1 THEN 'Fraud'
        ELSE 'Normal'
    END AS TRANSACTION_TYPE
FROM TRANSACTIONS
ORDER BY TRANSACTION_AMOUNT DESC;