SELECT
    FC.CASE_ID,
    FC.TRANSACTION_ID,
    C.CUSTOMER_NAME,
    FC.FRAUD_TYPE,
    FR.RULE_NAME,
    FR.SEVERITY,
    FC.CASE_STATUS,
    FC.INVESTIGATION_DATE,
    FC.RESOLUTION,
    T.AMOUNT,
    T.TRANSACTION_TIME
FROM FRAUD_CASES FC
JOIN TRANSACTIONS T
ON FC.TRANSACTION_ID = T.TRANSACTION_ID
JOIN ACCOUNTS A
ON T.ACCOUNT_ID = A.ACCOUNT_ID
JOIN CUSTOMERS C
ON A.CUSTOMER_ID = C.CUSTOMER_ID
JOIN FRAUD_RULES FR
ON FC.RULE_ID = FR.RULE_ID;

SELECT
    FR.RULE_NAME,
    FR.SEVERITY,
    COUNT(FC.CASE_ID) AS TOTAL_CASES
FROM FRAUD_RULES FR
LEFT JOIN FRAUD_CASES FC
ON FR.RULE_ID = FC.RULE_ID
GROUP BY FR.RULE_ID, FR.RULE_NAME, FR.SEVERITY
ORDER BY TOTAL_CASES DESC;