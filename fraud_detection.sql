SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    A.ACCOUNT_ID,
    A.ACCOUNT_TYPE,
    A.BALANCE
FROM CUSTOMERS C
JOIN ACCOUNTS A
ON C.CUSTOMER_ID = A.CUSTOMER_ID;

SELECT
    T.TRANSACTION_ID,
    A.ACCOUNT_ID,
    C.CUSTOMER_NAME,
    T.AMOUNT,
    T.TRANSACTION_TIME
FROM TRANSACTIONS T
JOIN ACCOUNTS A
ON T.ACCOUNT_ID = A.ACCOUNT_ID
JOIN CUSTOMERS C
ON A.CUSTOMER_ID = C.CUSTOMER_ID;

SELECT
    T.TRANSACTION_ID,
    C.CUSTOMER_NAME,
    M.MERCHANT_NAME,
    L.CITY AS TRANSACTION_CITY,
    P.PAYMENT_METHOD_NAME,
    T.AMOUNT
FROM TRANSACTIONS T
JOIN ACCOUNTS A
ON T.ACCOUNT_ID = A.ACCOUNT_ID
JOIN CUSTOMERS C
ON A.CUSTOMER_ID = C.CUSTOMER_ID
JOIN MERCHANTS M
ON T.MERCHANT_ID = M.MERCHANT_ID
JOIN LOCATIONS L
ON T.LOCATION_ID = L.LOCATION_ID
JOIN PAYMENT_METHODS P
ON T.PAYMENT_METHOD_ID = P.PAYMENT_METHOD_ID;

SELECT
    T.TRANSACTION_ID,
    C.CUSTOMER_NAME,
    T.AMOUNT
FROM TRANSACTIONS T
JOIN ACCOUNTS A
ON T.ACCOUNT_ID = A.ACCOUNT_ID
JOIN CUSTOMERS C
ON A.CUSTOMER_ID = C.CUSTOMER_ID
WHERE T.AMOUNT >
(
    SELECT AVG(T2.AMOUNT)
    FROM TRANSACTIONS T2
    WHERE T2.ACCOUNT_ID = T.ACCOUNT_ID
) * 3;

SELECT
    ACCOUNT_ID,
    AMOUNT,
    CASE
        WHEN AMOUNT >= 10000 THEN 'HIGH RISK'
        WHEN AMOUNT >= 5000 THEN 'MEDIUM RISK'
        ELSE 'LOW RISK'
    END AS RISK_LEVEL
FROM TRANSACTIONS;

SELECT
    T.TRANSACTION_ID,
    T.ACCOUNT_ID,
    T.AMOUNT,
    CASE
        WHEN T.AMOUNT >
        (
            SELECT AVG(T2.AMOUNT)
            FROM TRANSACTIONS T2
            WHERE T2.ACCOUNT_ID = T.ACCOUNT_ID
        ) * 3
        THEN 'POSSIBLE FRAUD'
        ELSE 'NORMAL'
    END AS FRAUD_STATUS
FROM TRANSACTIONS T;

SELECT
    T.TRANSACTION_ID,
    T.ACCOUNT_ID,
    T.AMOUNT,
    AVERAGE_DATA.AVG_AMOUNT
FROM TRANSACTIONS T
JOIN
(
    SELECT ACCOUNT_ID, AVG(AMOUNT) AS AVG_AMOUNT
    FROM TRANSACTIONS
    GROUP BY ACCOUNT_ID
) AVERAGE_DATA
ON T.ACCOUNT_ID = AVERAGE_DATA.ACCOUNT_ID
WHERE T.AMOUNT > AVERAGE_DATA.AVG_AMOUNT * 3;

SELECT
    T1.TRANSACTION_ID AS TRANSACTION_1,
    T2.TRANSACTION_ID AS TRANSACTION_2,
    T1.ACCOUNT_ID,
    T1.LOCATION_ID AS LOCATION_1,
    T2.LOCATION_ID AS LOCATION_2,
    TIMESTAMPDIFF(MINUTE,T1.TRANSACTION_TIME,T2.TRANSACTION_TIME) AS MINUTES_DIFFERENCE
FROM TRANSACTIONS T1
JOIN TRANSACTIONS T2
ON T1.ACCOUNT_ID = T2.ACCOUNT_ID
AND T1.TRANSACTION_ID < T2.TRANSACTION_ID
WHERE T1.LOCATION_ID <> T2.LOCATION_ID
AND TIMESTAMPDIFF(MINUTE,T1.TRANSACTION_TIME,T2.TRANSACTION_TIME) <= 10;

SELECT
    T1.TRANSACTION_ID AS TRANSACTION_1,
    T2.TRANSACTION_ID AS TRANSACTION_2,
    T1.ACCOUNT_ID,
    T1.MERCHANT_ID,
    T1.AMOUNT,
    TIMESTAMPDIFF(MINUTE,T1.TRANSACTION_TIME,T2.TRANSACTION_TIME) AS MINUTES_DIFFERENCE
FROM TRANSACTIONS T1
JOIN TRANSACTIONS T2
ON T1.ACCOUNT_ID = T2.ACCOUNT_ID
AND T1.MERCHANT_ID = T2.MERCHANT_ID
AND T1.AMOUNT = T2.AMOUNT
AND T1.TRANSACTION_ID < T2.TRANSACTION_ID
WHERE TIMESTAMPDIFF(MINUTE,T1.TRANSACTION_TIME,T2.TRANSACTION_TIME) <= 5;

SELECT
    T1.TRANSACTION_ID AS TRANSACTION_1,
    T2.TRANSACTION_ID AS TRANSACTION_2,
    T1.ACCOUNT_ID,
    TIMESTAMPDIFF(SECOND,T1.TRANSACTION_TIME,T2.TRANSACTION_TIME) AS SECONDS_DIFFERENCE
FROM TRANSACTIONS T1
JOIN TRANSACTIONS T2
ON T1.ACCOUNT_ID = T2.ACCOUNT_ID
AND T1.TRANSACTION_ID < T2.TRANSACTION_ID
WHERE TIMESTAMPDIFF(SECOND,T1.TRANSACTION_TIME,T2.TRANSACTION_TIME) <= 120;

